#!/usr/bin/env node
// Turns helper/exercise-pages/<lang>/<category>/*.md into app/services/reference/referencePages.generated.ts
const fs = require('fs');
const path = require('path');
const root = path.resolve(__dirname, '..', 'exercise-pages');
const pages = [];
for (const lang of ['en', 'ru'])
  for (const category of fs.readdirSync(path.join(root, lang)).sort())
    for (const file of fs.readdirSync(path.join(root, lang, category)).sort())
      pages.push({ lang, category, name: file.replace(/\.md$/, ''), content: fs.readFileSync(path.join(root, lang, category, file), 'utf8') });
const out = path.resolve(__dirname, '../../app/services/reference/referencePages.generated.ts');
fs.writeFileSync(out, `
// Generated by helper/tools/build-reference-module.js from helper/exercise-pages. Do not edit by hand.

export interface ReferencePage {
  lang: "en" | "ru";
  category: string;
  /** File name without extension */
  name: string;
  content: string;
}

export const REFERENCE_PAGES: readonly ReferencePage[] = ${JSON.stringify(pages, null, 2)};
`);
console.log('pages', pages.length, 'bytes', fs.statSync(out).size);

// ---- program (days A/B/C, H1-H3) as data: exercise names per language ----
const Helper = require(path.resolve(__dirname, '../workout-helper/main.js'));
const { WORKOUT_PROGRAM, EXERCISES_DATABASE } = Helper.__data;
const I = Helper.__i18n;
const nameOf = (id, lang) => I.EXERCISE_TEXT[lang][id].name;
const days = WORKOUT_PROGRAM.map((d) => ({
  key: d.key,
  cardio: !!d.cardio,
  timer: d.timer || null,
  blocks: d.blocks.map((b) => ({
    kind: b.kind,
    items: b.items.map((it) => ({
      category: EXERCISES_DATABASE.find((e) => e.id === it.id).category,
      name: { en: nameOf(it.id, 'en'), ru: nameOf(it.id, 'ru') },
      sides: !!it.sides,
    })),
  })),
}));
const pout = path.resolve(__dirname, '../../app/services/reference/referenceProgram.generated.ts');
fs.writeFileSync(pout, `// Generated by helper/tools/build-reference-module.js from the Workout Helper program. Do not edit by hand.

export interface ProgramItem {
  category: string;
  name: { en: string; ru: string };
  sides: boolean;
}

export interface ProgramBlock {
  kind: "single" | "superset" | "alt";
  items: ProgramItem[];
}

export interface ProgramDay {
  key: string;
  cardio: boolean;
  timer: { work: number; rest: number; roundRest: number; rounds: [number, number] } | null;
  blocks: ProgramBlock[];
}

export const REFERENCE_PROGRAM: readonly ProgramDay[] = ${JSON.stringify(days, null, 2)};
`);
console.log('days', days.length);
