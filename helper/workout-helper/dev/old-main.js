module.exports = class WorkoutTrackerPlugin extends Plugin {
  async onload() {
    this.registerView(VIEW_TYPE, (leaf) => new WorkoutView(leaf));

    this.addRibbonIcon('dumbbell', 'Открыть Workout Vault', () => this.activateView());

    this.addCommand({
      id: 'open-workout-vault',
      name: 'Открыть Workout Vault',
      callback: () => this.activateView(),
    });
  }

  onunload() {
    this.app.workspace.detachLeavesOfType(VIEW_TYPE);
  }

  async activateView() {
    const { workspace } = this.app;
    let leaf = workspace.getLeavesOfType(VIEW_TYPE)[0];

    if (!leaf) {
      leaf = workspace.getLeaf('tab');
      await leaf.setViewState({ type: VIEW_TYPE, active: true });
    }
    workspace.revealLeaf(leaf);
  }
};

