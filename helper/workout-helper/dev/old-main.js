class WorkoutView extends ItemView {
  constructor(leaf) {
    super(leaf);
    this.route = { name: 'dashboard' };
  }

  getViewType() {
    return VIEW_TYPE;
  }

  getDisplayText() {
    return 'Workout Vault';
  }

  getIcon() {
    return 'dumbbell';
  }

  async onOpen() {
    this.contentEl.addClass('wt-root');
    this.render();
  }

  async onClose() {
    this.destroyTimer();
    this.contentEl.empty();
  }

  go(route) {
    this.route = route;
    this.render();
    this.contentEl.scrollTop = 0;
  }

  openExercise(id) {
    const ex = getExercise(id);
    if (ex) new ExerciseModal(this.app, ex).open();
  }

  destroyTimer() {
    if (this.timer) {
      this.timer.destroy();
      this.timer = null;
    }
  }

  render() {
    this.destroyTimer();
    const root = this.contentEl;
    root.empty();

    switch (this.route.name) {
      case 'category':
        this.renderCategory(root, this.route.key);
        break;
      case 'day':
        this.renderDay(root, this.route.key);
        break;
      default:
        this.renderDashboard(root);
    }
  }

  /* ---------- Шапка ---------- */
  renderHeader(root, title, withBack) {
    const header = root.createDiv({ cls: 'wt-header' });
    if (withBack) {
      const back = header.createEl('button', { cls: 'wt-back', text: '← На главную' });
      back.addEventListener('click', () => this.go({ name: 'dashboard' }));
    }
    header.createEl('h1', { text: title });
  }

  /* ---------- Dashboard ---------- */
  renderDashboard(root) {
    this.renderHeader(root, '🏋️ Workout Vault', false);
    root.createEl('p', {
      cls: 'wt-subtitle',
      text: 'Домашние тренировки. Выбери силовой день, кардио или группу мышц.',
    });

    const renderDayCards = (container, list) => {
      list.forEach((day) => {
        const card = container.createDiv({ cls: 'wt-card wt-day-card ' + day.cls });
        card.createDiv({ cls: 'wt-card-icon', text: day.icon });
        card.createDiv({ cls: 'wt-card-title', text: day.title });
        card.createDiv({
          cls: 'wt-card-meta',
          text: day.meta || countExercisesInDay(day) + ' упражнений',
        });
        makeClickable(card, () => this.go({ name: 'day', key: day.key }));
      });
    };

    root.createEl('h2', { cls: 'wt-section-title', text: 'Силовые тренировки' });
    renderDayCards(
      root.createDiv({ cls: 'wt-grid' }),
      WORKOUT_PROGRAM.filter((d) => !d.cardio)
    );

    root.createEl('h2', { cls: 'wt-section-title', text: 'Кардио (HIIT)' });
    renderDayCards(
      root.createDiv({ cls: 'wt-grid' }),
      WORKOUT_PROGRAM.filter((d) => d.cardio)
    );

    root.createEl('h2', { cls: 'wt-section-title', text: 'Группы мышц' });
    const cats = root.createDiv({ cls: 'wt-grid' });
    CATEGORIES.forEach((cat) => {
      const count = EXERCISES_DATABASE.filter((e) => e.category === cat.key).length;
      const card = cats.createDiv({ cls: 'wt-card' });
      card.createDiv({ cls: 'wt-card-icon', text: cat.icon });
      card.createDiv({ cls: 'wt-card-title', text: cat.title });
      card.createDiv({ cls: 'wt-card-meta', text: 'Упражнений: ' + count });
      makeClickable(card, () => this.go({ name: 'category', key: cat.key }));
    });
  }

  /* ---------- Категория ---------- */
  renderCategory(root, key) {
    const cat = getCategory(key);
    this.renderHeader(root, cat ? cat.icon + ' ' + cat.title : 'Категория', true);

    const list = root.createDiv({ cls: 'wt-list' });
    EXERCISES_DATABASE.filter((e) => e.category === key).forEach((ex) => {
      const row = list.createDiv({ cls: 'wt-row' });
      const left = row.createDiv();
      left.createDiv({ cls: 'wt-row-name', text: ex.name });
      left.createDiv({ cls: 'wt-row-muscles', text: ex.muscles });
      makeClickable(row, () => this.openExercise(ex.id));
    });
  }

  /* ---------- День ---------- */
  renderDay(root, key) {
    const day = WORKOUT_PROGRAM.find((d) => d.key === key);
    if (!day) {
      this.go({ name: 'dashboard' });
      return;
    }

    this.renderHeader(root, day.icon + ' ' + day.title, true);
    root.createEl('p', {
      cls: 'wt-subtitle',
      text: 'Нажми на упражнение, чтобы открыть технику, безопасность и видео.',
    });

    if (day.info) {
      const info = root.createDiv({ cls: 'wt-callout wt-callout-info' });
      day.info.forEach((line) => info.createDiv({ text: line }));
    }

    if (day.timer) {
      const names = [];
      day.blocks.forEach((b) =>
        b.items.forEach((it) => {
          const ex = getExercise(it.id);
          if (ex) names.push({ name: ex.name, sides: !!it.sides });
        })
      );
      this.timer = new IntervalTimer(root, day.timer, names);
    }

    day.blocks.forEach((block) => {
      const wrap = root.createDiv({ cls: 'wt-block' });
      const label = wrap.createDiv({ cls: 'wt-block-label' });
      label.createSpan({ text: block.label });
      if (block.kind === 'superset') label.createSpan({ cls: 'wt-badge', text: 'суперсет' });

      const list = wrap.createDiv({ cls: 'wt-list' });
      block.items.forEach((item, idx) => {
        if (block.kind === 'alt' && idx > 0) {
          list.createDiv({ cls: 'wt-or', text: '— или —' });
        }
        const ex = getExercise(item.id);
        if (!ex) return;

        const row = list.createDiv({ cls: 'wt-row' });
        const left = row.createDiv();
        left.createDiv({ cls: 'wt-row-name', text: ex.name });
        left.createDiv({ cls: 'wt-row-muscles', text: ex.muscles });
        row.createDiv({ cls: 'wt-row-scheme', text: item.scheme });
        makeClickable(row, () => this.openExercise(ex.id));
      });
    });

    root.createDiv({
      cls: 'wt-note',
      text: day.note || 'Тренировки проводятся через день (например, Пн / Ср / Пт).',
    });
  }
}

