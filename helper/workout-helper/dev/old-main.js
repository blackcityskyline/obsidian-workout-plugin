/* ==========================================================
 * ИНТЕРВАЛЬНЫЙ ТАЙМЕР (для кардио-дней)
 * cfg: { work, rest, roundRest (сек), rounds: [варианты], restLabel? }
 * names: [{ name, sides }]; sides — сигнал смены стороны на середине работы.
 * ========================================================== */
class IntervalTimer {
  constructor(container, cfg, names) {
    this.cfg = cfg;
    this.names = names;
    this.rounds = cfg.rounds[0];
    this.handle = null;
    this.audio = null;
    this.build(container);
    this.reset();
  }

  build(container) {
    const box = container.createDiv({ cls: 'wt-timer' });
    this.box = box;
    box.createDiv({ cls: 'wt-timer-title', text: '⏱ Интервальный таймер' });

    const sel = box.createDiv({ cls: 'wt-timer-rounds' });
    sel.createSpan({ text: 'Кругов:' });
    this.roundBtns = this.cfg.rounds.map((n) => {
      const b = sel.createEl('button', { cls: 'wt-timer-round-btn', text: String(n) });
      b.addEventListener('click', () => {
        this.rounds = n;
        this.reset();
      });
      return b;
    });

    this.phaseEl = box.createDiv({ cls: 'wt-timer-phase' });
    this.timeEl = box.createDiv({ cls: 'wt-timer-time' });
    this.exEl = box.createDiv({ cls: 'wt-timer-ex' });
    this.metaEl = box.createDiv({ cls: 'wt-timer-meta' });

    const controls = box.createDiv({ cls: 'wt-timer-controls' });
    this.startBtn = controls.createEl('button', { cls: 'mod-cta', text: 'Старт' });
    this.skipBtn = controls.createEl('button', { text: 'Пропустить' });
    this.resetBtn = controls.createEl('button', { text: 'Сброс' });
    this.startBtn.addEventListener('click', () => this.toggle());
    this.skipBtn.addEventListener('click', () => this.skip());
    this.resetBtn.addEventListener('click', () => this.reset());
  }

  buildSteps() {
    const { work, rest, roundRest } = this.cfg;
    const n = this.names.length;
    const steps = [];
    for (let r = 1; r <= this.rounds; r++) {
      for (let i = 0; i < n; i++) {
        steps.push({
          type: 'work',
          dur: work,
          round: r,
          ex: i,
          sides: !!this.names[i].sides,
        });
        if (i < n - 1) {
          if (rest > 0) steps.push({ type: 'rest', dur: rest, round: r, ex: i + 1 });
        } else if (r < this.rounds) {
          steps.push({ type: 'roundRest', dur: roundRest, round: r + 1, ex: 0 });
        }
      }
    }
    return steps;
  }

  reset() {
    this.stopTicking();
    this.steps = this.buildSteps();
    this.idx = 0;
    this.running = false;
    this.finished = false;
    this.midDone = false;
    this.remaining = this.steps[0].dur * 1000;
    this.startBtn.setText('Старт');
    this.roundBtns.forEach((b, i) => {
      if (this.cfg.rounds[i] === this.rounds) b.addClass('is-active');
      else b.removeClass('is-active');
    });
    this.render();
  }

  toggle() {
    if (this.finished) this.reset();
    if (this.running) {
      this.pause();
      return;
    }
    this.unlockAudio();
    this.running = true;
    this.endAt = Date.now() + this.remaining;
    this.handle = setInterval(() => this.tick(), 200);
    this.startBtn.setText('Пауза');
    this.beep(660, 150);
    this.render();
  }

  pause() {
    this.remaining = Math.max(0, this.endAt - Date.now());
    this.running = false;
    this.stopTicking();
    this.startBtn.setText('Продолжить');
    this.render();
  }

  skip() {
    if (this.finished) return;
    this.goTo(this.idx + 1, Date.now());
  }

  tick() {
    this.remaining = this.endAt - Date.now();
    const step = this.steps[this.idx];
    if (step.type === 'work' && step.sides && !this.midDone && this.remaining <= step.dur * 500) {
      this.midDone = true;
      this.beep(880, 250);
    }
    if (this.remaining <= 0) {
      this.goTo(this.idx + 1, this.endAt);
      return;
    }
    this.render();
  }

  goTo(idx, startFrom) {
    this.midDone = false;
    if (idx >= this.steps.length) {
      this.finish();
      return;
    }
    this.idx = idx;
    const dur = this.steps[idx].dur * 1000;
    if (this.running) {
      this.endAt = startFrom + dur;
      this.remaining = this.endAt - Date.now();
    } else {
      this.remaining = dur;
    }
    this.beep(this.steps[idx].type === 'work' ? 880 : 440, 300);
    this.render();
  }

  finish() {
    this.stopTicking();
    this.running = false;
    this.finished = true;
    this.remaining = 0;
    this.startBtn.setText('Заново');
    this.beep(1000, 600);
    this.render();
  }

  render() {
    this.box.removeClass('is-work');
    this.box.removeClass('is-rest');

    if (this.finished) {
      this.phaseEl.setText('ГОТОВО');
      this.timeEl.setText('00:00');
      this.exEl.setText('Тренировка завершена. Хорошая работа!');
      this.metaEl.setText('');
      return;
    }

    const step = this.steps[this.idx];
    const secs = Math.max(0, Math.ceil(this.remaining / 1000));
    const mm = String(Math.floor(secs / 60)).padStart(2, '0');
    const ss = String(secs % 60).padStart(2, '0');
    this.timeEl.setText(mm + ':' + ss);

    const labels = {
      work: 'РАБОТА',
      rest: this.cfg.restLabel || 'ОТДЫХ',
      roundRest: 'ОТДЫХ МЕЖДУ КРУГАМИ',
    };
    this.phaseEl.setText(labels[step.type]);

    const cur = this.names[step.ex];
    if (step.type === 'work') {
      let text = cur.name;
      if (cur.sides) text += this.midDone ? ' · смена стороны' : ' · первая сторона';
      this.exEl.setText(text);
    } else {
      this.exEl.setText('Дальше: ' + cur.name);
    }

    this.metaEl.setText(
      'Круг ' + step.round + ' из ' + this.rounds +
        ' · упражнение ' + (step.ex + 1) + ' из ' + this.names.length
    );
    this.box.addClass(step.type === 'work' ? 'is-work' : 'is-rest');
  }

  stopTicking() {
    if (this.handle !== null) {
      clearInterval(this.handle);
      this.handle = null;
    }
  }

  destroy() {
    this.stopTicking();
    try {
      if (this.audio) this.audio.close();
    } catch (e) {
      /* звук недоступен */
    }
    this.audio = null;
  }

  unlockAudio() {
    try {
      const AC = window.AudioContext || window.webkitAudioContext;
      if (!AC) return;
      if (!this.audio) this.audio = new AC();
      if (this.audio.state === 'suspended') this.audio.resume();
    } catch (e) {
      /* звук недоступен */
    }
  }

  beep(freq, ms) {
    try {
      if (this.audio) {
        const osc = this.audio.createOscillator();
        const gain = this.audio.createGain();
        osc.frequency.value = freq;
        gain.gain.value = 0.15;
        osc.connect(gain);
        gain.connect(this.audio.destination);
        osc.start();
        osc.stop(this.audio.currentTime + ms / 1000);
      }
    } catch (e) {
      /* звук недоступен */
    }
    try {
      if (typeof navigator !== 'undefined' && navigator.vibrate) {
        navigator.vibrate(Math.min(ms, 300));
      }
    } catch (e) {
      /* вибрация недоступна */
    }
  }
}

